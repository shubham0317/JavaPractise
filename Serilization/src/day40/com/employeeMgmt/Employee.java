package day40.com.employeeMgmt;

import java.io.Serializable;
import java.util.Objects;

public class Employee implements Serializable{
	
	private static final long serialVersionUID = 1L;
	private String employeeId;
	private transient String employeeName;
	private String department;
	private double salary;
	public Employee(String employeeId, String employeeName, String department, double salary) {
		super();
		this.employeeId = employeeId;
		this.employeeName = employeeName;
		this.department = department;
		this.salary = salary;
	}
	public String getEmployeeId() {
		return employeeId;
	}
	public void setEmployeeId(String employeeId) {
		this.employeeId = employeeId;
	}
	public String getEmployeeName() {
		return employeeName;
	}
	public void setEmployeeName(String employeeName) {
		this.employeeName = employeeName;
	}
	public String getDepartment() {
		return department;
	}
	public void setDepartment(String department) {
		this.department = department;
	}
	public double getSalary() {
		return salary;
	}
	public void setSalary(double salary) {
		this.salary = salary;
	}
	@Override
	public String toString() {
		return "Employee [employeeId=" + employeeId + ", department=" + department + ", salary=" + salary + "]";
	}

}
