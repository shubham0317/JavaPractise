package day19.kodewala.array;

public class User {

	String name;
	String phoneNo;
	
	public User(String name, String phoneNo) {
		super();
		this.name = name;
		this.phoneNo = phoneNo;
	}

	@Override
	public String toString() {
		return "User [name=" + name + ", phoneNo=" + phoneNo + "]";
	}

	
	
	
	
}
