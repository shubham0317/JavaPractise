package day24.kodewala.string.practise;

public class Practise7 {
   public static void main(String[] args) {
	   final String a = "Hello";
	   final String b = "World";

	   String c = a + b;
	   String d = "HelloWorld";

	   System.out.println(c == d);
	   
	   
	   String e = "Hello";
	   String f = "World";

	   String g = e + f;
	   String i = "HelloWorld";

	   System.out.println(g == i);
   }
}
